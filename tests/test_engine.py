#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""test_engine.py -- black-box regression checks for the pdf-parse skill.

    python tests/test_engine.py            # run every case
    python tests/test_engine.py cjk        # only cases whose name matches

No pytest, no network, no scoring endpoint.  Each assertion prints one ASCII
line `PASS  <case>  <assertion>` or `FAIL  <case>  <assertion>  [detail]`.
Exit code 1 if anything failed.

The three fixtures are generated by `outputs/scripts/make_fixtures.py`; they are
synthetic (see tests/README.md).  Nothing here measures a vision model: the
scanned case feeds the *known* source text of the synthetic page into the merge
pipeline, so it tests the merge contract, not OCR accuracy.
"""
from __future__ import annotations

import io
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BUNDLE = os.path.dirname(HERE)
SCRIPTS = os.path.join(BUNDLE, "outputs", "scripts")
FIXTURES = os.path.join(HERE, "fixtures")
WORK = os.path.join(HERE, "_work")
PY = sys.executable

sys.path.insert(0, SCRIPTS)

RESULTS = []      # (case, assertion, ok, detail)


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #
def check(case, assertion, ok, detail=""):
    RESULTS.append((case, assertion, bool(ok), detail))


def ascii_safe(s):
    """Console is GBK on the target box: keep stdout pure ASCII.  Non-ASCII
    (the CJK heading literals) is escaped as \\uXXXX so the expected string
    stays exact and unambiguous instead of turning into '??'."""
    return str(s).encode("ascii", "backslashreplace").decode("ascii")


def norm(s):
    """Compare text ignoring the non-breaking / ideographic spaces a PDF font
    may put where the source had an ASCII space."""
    if not s:
        return ""
    for ch in ("\u00a0", "\u3000", "\u2007", "\u202f"):
        s = s.replace(ch, " ")
    return " ".join(s.split())


def run(args, **kw):
    env = dict(os.environ, PYTHONIOENCODING="utf-8")
    return subprocess.run(args, capture_output=True, text=True, encoding="utf-8",
                          errors="replace", env=env, **kw)


def load(path):
    with io.open(path, encoding="utf-8") as fh:
        return json.load(fh)


def ensure_fixtures():
    need = [os.path.join(FIXTURES, n) for n in
            ("cjk-2col.pdf", "title-wrap.pdf", "scanned.pdf")]
    if all(os.path.exists(p) for p in need):
        return True
    p = run([PY, os.path.join(SCRIPTS, "make_fixtures.py")])
    return p.returncode == 0


def parse(case, pdf, out, extra=()):
    os.makedirs(out, exist_ok=True)
    p = run([PY, os.path.join(SCRIPTS, "parse_pdf.py"), pdf, "--out", out,
             "--no-overlay"] + list(extra))
    return p


# --------------------------------------------------------------------------- #
# case 1: Chinese two-column page
# --------------------------------------------------------------------------- #
def case_cjk():
    case = "cjk-2col"
    pdf = os.path.join(FIXTURES, "cjk-2col.pdf")
    out = os.path.join(WORK, "cjk")
    p = parse(case, pdf, out)
    check(case, "parse_pdf exit=0", p.returncode == 0,
          "exit=%d %s" % (p.returncode, (p.stderr or p.stdout)[-200:]))
    doc_path = os.path.join(out, "doc.json")
    if not os.path.exists(doc_path):
        check(case, "doc.json written", False, "missing")
        return
    doc = load(doc_path)
    pages, blocks, secs = doc["pages"], doc["blocks"], doc["sections"]

    check(case, "body page columns==2", pages and pages[0]["columns"] == 2,
          "columns=%s" % [x.get("columns") for x in pages])

    paths = [norm(s["path"]) for s in secs]
    check(case, "section path has '1 引言'", "1 引言" in paths, "paths=%s" % paths)
    check(case, "section path has '2 相关工作 / 2.1 检索增强'",
          "2 相关工作 / 2.1 检索增强" in paths, "paths=%s" % paths)

    cr = doc["stats"].get("char_recall")
    check(case, "0.90 <= char_recall <= 1.05", cr is not None and 0.90 <= cr <= 1.05,
          "char_recall=%s" % cr)

    check(case, "selfcheck.ok", doc["selfcheck"]["ok"] is True,
          "errors=%s" % doc["selfcheck"]["errors"])

    # the 3x3 grid must be structured, or explicitly rejected while its text
    # stays in the body -- it may never vanish
    structured = [t for t in doc["tables"] if t.get("n_rows", 0) >= 2]
    cells = ["模型", "准确率", "参数量", "基线", "82.1", "12M",
             "本文", "85.4", "9M"]
    emitted = norm(" ".join(b["text"] for b in blocks
                            if b["type"] not in ("figure_label", "margin_artifact")))
    if structured:
        check(case, "3x3 table structured (n_rows>=2)",
              structured[0]["n_rows"] == 3 and structured[0]["n_cols"] == 3,
              "n_rows=%d n_cols=%d" % (structured[0]["n_rows"], structured[0]["n_cols"]))
    else:
        check(case, "table rejected but its text kept in body",
              bool(doc["tables_rejected"]) and all(c in emitted for c in cells),
              "rejected=%d missing=%s" % (
                  len(doc["tables_rejected"]),
                  [c for c in cells if c not in emitted]))

    gutters = pages[0].get("gutters") or []
    crossers = []
    for b in blocks:
        if b.get("column", -1) < 0:
            continue
        for g0, g1 in gutters:
            if b["bbox"][0] < g1 - 1 and b["bbox"][2] > g0 + 1:
                crossers.append((b["id"], b["column"]))
    check(case, "no column block crosses the gutter", not crossers,
          "crossers=%s" % crossers)


# --------------------------------------------------------------------------- #
# case 2: two-line title + ALL-CAPS subsection at body size
# --------------------------------------------------------------------------- #
def case_title_wrap():
    case = "title-wrap"
    pdf = os.path.join(FIXTURES, "title-wrap.pdf")
    out = os.path.join(WORK, "title-wrap")
    p = parse(case, pdf, out)
    check(case, "parse_pdf exit=0", p.returncode == 0,
          "exit=%d %s" % (p.returncode, (p.stderr or p.stdout)[-200:]))
    doc_path = os.path.join(out, "doc.json")
    if not os.path.exists(doc_path):
        check(case, "doc.json written", False, "missing")
        return
    doc = load(doc_path)
    from make_fixtures import EN_TITLE_1, EN_TITLE_2

    title = norm((doc["metadata"].get("title") or {}).get("text"))
    check(case, "metadata.title.text holds both title lines",
          norm(EN_TITLE_1) in title and norm(EN_TITLE_2) in title,
          "title=%r" % title)

    codes = [w.get("code") for w in doc["warnings"]]
    check(case, "warnings include title_merged", "title_merged" in codes,
          "codes=%s" % codes)

    lvl2 = [s for s in doc["sections"]
            if norm(s["title"]).upper() == "2.1 SETUP AND METRICS"]
    check(case, "'2.1 SETUP AND METRICS' is a level-2 section",
          len(lvl2) == 1 and lvl2[0]["level"] == 2,
          "found=%s" % [(s["title"], s["level"]) for s in doc["sections"]])

    phantom = [s for s in doc["sections"] if norm(s["title"]) == norm(EN_TITLE_2)]
    check(case, "no phantom section from title line 2", not phantom,
          "phantom=%s" % [s["title"] for s in phantom])


# --------------------------------------------------------------------------- #
# case 3: no text layer -> OCR/vision branch -> merge
# --------------------------------------------------------------------------- #
def case_scanned():
    case = "scanned"
    pdf = os.path.join(FIXTURES, "scanned.pdf")
    out = os.path.join(WORK, "scanned")
    p = parse(case, pdf, out)
    check(case, "parse_pdf exit=3 (no text layer)", p.returncode == 3,
          "exit=%d" % p.returncode)

    o = run([PY, os.path.join(SCRIPTS, "ocr_pages.py"), pdf, "--out", out,
             "--dpi", "200"])
    check(case, "ocr_pages exit=0", o.returncode == 0,
          "exit=%d %s" % (o.returncode, (o.stderr or "")[-200:]))
    ocr = os.path.join(out, "ocr")
    for rel in ("page-01.png", "prompt-01.md", "index.json"):
        check(case, "ocr_pages wrote ocr/%s" % rel,
              os.path.exists(os.path.join(ocr, rel)), "missing")

    idx_path = os.path.join(ocr, "index.json")
    if os.path.exists(idx_path):
        idx = load(idx_path)
        check(case, "ocr/index.json lists page 1 image",
              any(it.get("page") == 1 and it.get("image", "").endswith("page-01.png")
                  for it in idx.get("pages", [])),
              "pages=%s" % [it.get("page") for it in idx.get("pages", [])])

    # Ground truth of a synthetic page: the text that was rendered into it.
    from make_fixtures import (EN_TITLE_1, EN_TITLE_2, EN_AUTHORS, EN_AFFIL,
                               EN_ABSTRACT, EN_SECTIONS)
    lines = ["## page 1", "", "[header] " + EN_AFFIL, "",
             EN_TITLE_1 + " " + EN_TITLE_2, "", EN_AUTHORS, "",
             "Abstract", "", EN_ABSTRACT, ""]
    for head, _lvl, paras in EN_SECTIONS:
        lines.append(head)
        lines.append("")
        lines.extend(paras)
        lines.append("")
    lines.append("confidence: high")
    transcript = "\n".join(lines) + "\n"
    with io.open(os.path.join(ocr, "page-01.md"), "w", encoding="utf-8",
                 newline="\n") as fh:
        fh.write(transcript)

    m = run([PY, os.path.join(SCRIPTS, "merge_ocr.py"), out, "--require", "all"])
    check(case, "merge_ocr --require all exit=0", m.returncode == 0,
          "exit=%d %s" % (m.returncode, (m.stdout or m.stderr)[-200:]))

    doc = load(os.path.join(out, "doc.json"))
    blocks = doc["blocks"]
    check(case, "merged blocks exist", len(blocks) > 0, "n_blocks=%d" % len(blocks))
    check(case, "every merged block has bbox=null",
          all(b.get("bbox") is None for b in blocks),
          "with_bbox=%d" % sum(1 for b in blocks if b.get("bbox") is not None))
    check(case, "every merged block has bbox_source=vision",
          all(b.get("bbox_source") == "vision" for b in blocks),
          "sources=%s" % sorted({b.get("bbox_source") for b in blocks}))
    check(case, "every merged block has a confidence",
          all(b.get("confidence") for b in blocks),
          "conf=%s" % sorted({b.get("confidence") for b in blocks}))
    check(case, "stats.char_recall is None",
          doc["stats"].get("char_recall") is None,
          "char_recall=%r" % doc["stats"].get("char_recall"))
    ocr_pages = doc["stats"].get("ocr_pages") or []
    check(case, "stats.ocr_pages covers page 1",
          len(ocr_pages) >= 1 and 1 in ocr_pages, "ocr_pages=%s" % ocr_pages)
    check(case, "merged text keeps the page's source title",
          norm(EN_TITLE_1) in norm(" ".join(b["text"] for b in blocks)),
          "title line missing from merged blocks")


# --------------------------------------------------------------------------- #
CASES = [("cjk", case_cjk), ("title", case_title_wrap), ("scanned", case_scanned)]


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    os.makedirs(WORK, exist_ok=True)
    if not ensure_fixtures():
        print("FAIL  setup  fixtures could not be generated")
        return 1
    want = [c for c in CASES if not argv or any(a in c[0] for a in argv)]

    for _name, fn in want:
        try:
            fn()
        except Exception as exc:                     # noqa: BLE001
            check(_name, "case raised", False, "%s: %s" % (type(exc).__name__, exc))

    fails = 0
    for case, assertion, ok, detail in RESULTS:
        if ok:
            print("PASS  %-10s  %s" % (case, ascii_safe(assertion)))
        else:
            fails += 1
            print("FAIL  %-10s  %s  [%s]" % (case, ascii_safe(assertion),
                                             ascii_safe(detail)[:300]))
    print("")
    print("%d checks, %d failed" % (len(RESULTS), fails))

    log = os.path.join(WORK, "last_run.txt")
    with io.open(log, "w", encoding="utf-8", newline="\n") as fh:
        for case, assertion, ok, detail in RESULTS:
            fh.write("%s  %s  %s  %s\n" % ("PASS" if ok else "FAIL", case,
                                           assertion, detail))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
